def cap(attr,pos):
    i=src.find(attr+"=",pos)
    k=i+len(attr)+1
    while src[k] in " \t": k+=1
    if src[k]=="(":
        depth=0;in_str=False;j=k
        while j<len(src):
            c=src[j]
            if in_str:
                if c==chr(34): in_str=False
            else:
                if c==chr(34): in_str=True
                elif c=="(": depth+=1
                elif c==")":
                    depth-=1
                    if depth==0: return src[i:j+1]
            j+=1
        return src[i:j]
    endq=src.find(chr(34),k+1)
    return src[i:endq+1]
